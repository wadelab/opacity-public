"""The papers' generated inputs match the repository's record.

paper/numbers.tex (which paper-vetting/ links to), and each paper's models.tex
and instructions.tex, are committed so that both manuscripts build from a
clone, and regenerated by build.sh (paper/make_numbers.py, paper/instructions.py).
These tests regenerate them in check mode and fail on drift, so a stale number
or prompt cannot become prose. They skip where the run summaries are absent
(a checkout without runs/).
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"


def _check(script: str) -> None:
    proc = subprocess.run([sys.executable, str(PAPER / script), "--check"], capture_output=True, text=True, cwd=ROOT)
    assert proc.returncode == 0, f"{script} --check failed:\n{proc.stdout}\n{proc.stderr}"


@pytest.mark.skipif(not (ROOT / "runs" / "summary" / "sizing" / "fresh_results.csv").exists(),
                    reason="run summaries not present in this checkout")
def test_numbers_tex_matches_the_record() -> None:
    _check("make_numbers.py")


def test_instructions_tex_matches_the_code() -> None:
    _check("instructions.py")
