#!/usr/bin/env python
"""Write each paper's instructions.tex: the instructions the study ran, verbatim,
extracted from the package so that the appendix cannot drift from the code.
paper/ (Studies 1 and 2) and paper-vetting/ (the probe and bias tests) each
reproduce the instructions their runs used.

    .venv/bin/python paper/instructions.py
"""

from __future__ import annotations

import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from opacity.checker.prompts import REVIEWER_INSTRUCTION, SYSTEM_PREAMBLE  # noqa: E402
from opacity.harvest.prompts import (  # noqa: E402
    AGENT_INSTRUCTION,
    ANALYST_SYSTEM,
    DISGUISE_NOTE,
    JUDGE_INSTRUCTION,
    JUDGE_SYSTEM,
    STEER_NOTE_V2,
    STYLE_NOTES,
)
from opacity.variants import ANALYST_RULES  # noqa: E402

COMMON = [
    ("The reviewer instruction (every reviewer and checker; the system preamble first)", SYSTEM_PREAMBLE + "\n\n" + REVIEWER_INSTRUCTION),
    ("The standard analyst instruction (the system line first)", ANALYST_SYSTEM + "\n\n" + AGENT_INSTRUCTION),
    ("The design-first prompt (the rules prompt), appended to the standard instruction", ANALYST_RULES),
    ("The judge instruction (the system line first)", JUDGE_SYSTEM + "\n\n" + JUDGE_INSTRUCTION),
]
PAPERS = {
    ROOT / "paper" / "instructions.tex": COMMON,
    ROOT / "paper-vetting" / "instructions.tex": COMMON + [
        ("The bias instruction (the second steering note in the code), appended after the tables in the biased condition", STEER_NOTE_V2),
        ("The concise style request, after the tables in both conditions", STYLE_NOTES["concise"]),
        ("The thorough style request, after the tables in both conditions", STYLE_NOTES["thorough"]),
        ("The disguise request, after the bias instruction", DISGUISE_NOTE),
    ],
}


def wrap(text: str, width: int = 86) -> str:
    out = []
    for para in text.split("\n"):
        if not para.strip():
            out.append("")
            continue
        indent = len(para) - len(para.lstrip(" "))
        out.extend(textwrap.wrap(para, width=width, subsequent_indent=" " * (indent + 2),
                                 break_long_words=False, break_on_hyphens=False) or [""])
    return "\n".join(out)


def main() -> int:
    status = 0
    for out, blocks in PAPERS.items():
        parts = []
        for title, text in blocks:
            parts.append(f"\\paragraph{{{title}.}}\n\\begin{{footnotesize}}\\begin{{verbatim}}\n{wrap(text.rstrip())}\n\\end{{verbatim}}\n\\end{{footnotesize}}\n")
        text = "% Generated by paper/instructions.py from the package. Do not edit.\n" + "\n".join(parts)
        if "--check" in sys.argv:
            if (out.read_text() if out.exists() else "") != text:
                print(f"DRIFT: {out} differs from the code; run paper/instructions.py", file=sys.stderr)
                status = 1
            else:
                print("checked", out)
            continue
        out.write_text(text)
        print("wrote", out)
    return status


if __name__ == "__main__":
    raise SystemExit(main())
