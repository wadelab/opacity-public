"""Load the harvest tasks and render what the agent sees.

A task's `question` and `pack` are rendered for the agent. `invites`, `dgp`,
`correct` and `judge_notes` are the key and never enter the render;
`test_key_never_in_pack` checks every task.

The task sets in DECEPTION_TASK_SETS are generated by the deception study's
code, which is not part of this public release.

Tables with `rows` render as given. Tables with only a `note` are filled by
the generator registered for the task in generators.py; a table that reaches
the render with no rows is an error, so a specification can never be shown to
an agent in place of data.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from importlib.resources import files
from typing import Any

import numpy as np
import yaml

from . import generators

CLASS_NAMES = {
    1: "multiplicity",
    2: "silent attrition",
    3: "confounding",
    4: "unsupported causal claim",
    5: "wrong error structure",
    6: "wrong denominator",
    7: "regression to the mean",
    8: "in-sample performance",
}


@dataclass(frozen=True)
class HarvestTask:
    id: str
    domain: str
    invites: tuple[int, ...]
    question: str
    pack: dict[str, Any]
    dgp: str
    correct: str
    judge_notes: str
    extra: dict[str, Any] = field(default_factory=dict)
    """Added to each sample's metadata (the deception tasks' programme and
    family); empty for every YAML task set."""

    @property
    def primary_class(self) -> int:
        return self.invites[0] if self.invites else 0

    @property
    def invited_label(self) -> str:
        return "+".join(str(c) for c in self.invites) if self.invites else "control"


TASK_SETS = {"dev": "tasks.yaml", "heldout": "heldout.yaml", "fresh": "fresh.yaml", "fresh2": "fresh2.yaml"}
"""The 36 tasks every run so far used, the 36 held out for the
model-sizing study's confirmation (drafted, not yet human-reviewed), 36
fresh confirmation tasks (h73 to h108) written blind to the prompt variants
and the verifier, and a second blind confirmation set of 40 (h109 to h148:
32 seeded tasks whose traps are mostly visible only from the stated design,
and 8 controls whose real effects invite over-correction)."""


DECEPTION_TASK_SETS = {"deception-train": "train", "deception-validation": "validation"}
"""Task sets generated by the deception study's code rather than read from YAML
(not part of this public release)."""

DECEPTION_VIEW_SETS = {"deception-train-cview": "train"}
"""A further generated task set of the deception study (not part of this public release)."""


def task_from_dict(t: dict[str, Any]) -> HarvestTask:
    """One task from its mapping. Keys other than the harvest fields are ignored."""
    invites = tuple(int(c) for c in t.get("invites", []))
    assert all(1 <= c <= 8 for c in invites), (t["id"], invites)
    return HarvestTask(
        id=t["id"],
        domain=t["domain"],
        invites=invites,
        question=t["question"].strip(),
        pack=t.get("pack", {}),
        dgp=t.get("dgp", "").strip(),
        correct=t["correct"].strip(),
        judge_notes=t["judge_notes"].strip(),
        extra=dict(t.get("extra") or {}),
    )


class WithheldTaskSet(LookupError):
    """A task set the study uses that this public release does not include: the
    held-out and sealed sets stay private so they can still serve as vetting
    tests, and the deception study's generator is withheld until it ends."""


def load_tasks(path: str | None = None, task_set: str = "dev") -> list[HarvestTask]:
    if task_set in DECEPTION_TASK_SETS or task_set in DECEPTION_VIEW_SETS:
        if path:
            raise ValueError(f"{task_set!r} is generated, not read from a file")
        # imported here: the deception module imports this one
        try:
            from opacity.deception import families
        except ImportError:
            raise WithheldTaskSet(f"{task_set!r} is not part of the public release") from None

        raw = (families.tasks(DECEPTION_TASK_SETS[task_set]) if task_set in DECEPTION_TASK_SETS
               else families.completers_view_tasks(DECEPTION_VIEW_SETS[task_set]))
    else:
        if task_set not in TASK_SETS:
            raise ValueError(f"task_set must be one of "
                             f"{tuple(TASK_SETS) + tuple(DECEPTION_TASK_SETS) + tuple(DECEPTION_VIEW_SETS)}; "
                             f"got {task_set!r}")
        resource = files("opacity.harvest") / TASK_SETS[task_set]
        if not path and not resource.is_file():
            raise WithheldTaskSet(f"{task_set!r} is not part of the public release")
        text = open(path).read() if path else resource.read_text()
        raw = yaml.safe_load(text)["tasks"]
    out = [task_from_dict(t) for t in raw]
    ids = [t.id for t in out]
    assert len(ids) == len(set(ids)), "duplicate task ids"
    return out


@dataclass
class RenderedPack:
    text: str
    attempts: int = 1
    """Generator regenerations needed to satisfy the task's dgp constraint."""
    tables: list[dict[str, Any]] = field(default_factory=list)


def _fmt(v: Any) -> str:
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, (int, np.integer)):
        return f"{int(v):,}"
    if isinstance(v, (float, np.floating)):
        return f"{float(v):,.1f}" if abs(v) >= 100 else f"{float(v):.1f}" if float(v) != int(v) else f"{int(v)}"
    return str(v)


def _md_table(columns: list[str], rows: list[list[Any]]) -> str:
    head = "| " + " | ".join(str(c) for c in columns) + " |"
    sep = "|" + "|".join("---" for _ in columns) + "|"
    body = "\n".join("| " + " | ".join(_fmt(v) for v in r) + " |" for r in rows)
    return "\n".join([head, sep, body])


def render_pack(task: HarvestTask, seed: int = 0, replicate: int = 0) -> RenderedPack:
    """Render the request and data pack for one draw. Deterministic in
    (seed, task id, replicate)."""
    tables = [dict(t) for t in task.pack.get("tables", [])]
    attempts = 1
    gen = generators.GENERATORS.get(task.id)
    if gen is not None:
        rng = np.random.default_rng([seed, int(task.id[1:]), replicate])
        filled, attempts = gen(rng, tables)
        for t, rows in zip(tables, filled):
            if rows is not None:
                t["rows"] = rows
    for t in tables:
        if not t.get("rows"):
            raise ValueError(f"{task.id}: table {t.get('title')!r} has no rows and no generator")

    parts = ["## Request", "", task.question, "", "## Data pack", ""]
    stages = task.pack.get("stages")
    if stages:
        parts += ["### Sample stages", "", _md_table(["Stage", "n"], [list(s) for s in stages]), ""]
    for t in tables:
        parts += [f"### {t['title']}", "", _md_table(t["columns"], t["rows"]), ""]
    notes = task.pack.get("notes")
    if notes:
        parts += ["### Notes", ""] + [f"- {n}" for n in notes] + [""]
    return RenderedPack(text="\n".join(parts).rstrip() + "\n", attempts=attempts, tables=tables)
